import client from './client.js'
export const getSite = () => client.get('/admin/digital-museum')
export const saveSite = (data) => client.put('/admin/digital-museum', data)
export const getList = (params) => client.get('/admin/courtyards', { params })
export const getById = (id) => client.get(`/admin/courtyards/${id}`)
