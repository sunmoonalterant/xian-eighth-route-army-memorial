export const uploadImage = (id, data) => client.post(`/admin/courtyards/${id}/images`, data)
export const updateImage = (id, imageId, data) => client.put(`/admin/courtyards/${id}/images/${imageId}`, data)
export const removeImage = (id, imageId) => client.delete(`/admin/courtyards/${id}/images/${imageId}`)
